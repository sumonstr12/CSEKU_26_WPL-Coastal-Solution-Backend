def get_district_coords(district_name):
    """
    Returns (lat, lng) or (None, None).
    Handles case-insensitive match + whitespace trimming.
    """
    if not district_name:
        return None, None

    key = str(district_name).strip()

    # Exact match
    if key in DISTRICT_COORDS:
        return DISTRICT_COORDS[key]

    # Case-insensitive fallback
    lower = key.lower()
    for k, v in DISTRICT_COORDS.items():
        if k.lower() == lower:
            return v

    return None, None